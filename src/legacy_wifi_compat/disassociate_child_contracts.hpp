inline bool verifyRelativeBranch(const P::Image &image, size_t instruction,
                                 uintptr_t target, uint8_t opcode) {
    if (!P::range(image,instruction,5) || image.bytes[instruction] != opcode ||
        (opcode != 0xe8 && opcode != 0xe9) ||
        instruction > UINTPTR_MAX - image.base - 5) return false;
    const uintptr_t returnPC = image.base + instruction + 5;
    int64_t expected = 0;
    if (target >= returnPC) {
        const uint64_t distance = target - returnPC;
        if (distance > static_cast<uint64_t>(INT32_MAX)) return false;
        expected = static_cast<int64_t>(distance);
    } else {
        const uint64_t distance = returnPC - target;
        if (distance > 0x80000000ULL) return false;
        expected = -static_cast<int64_t>(distance);
    }
    int32_t actual = 0;
    memcpy(&actual,image.bytes + instruction + 1,sizeof(actual));
    return actual == expected;
}

inline bool verifyExternalBranch(const P::Image &image, ChildKind child,
                                 const ExternalCall &branch,
                                 uintptr_t target) {
    const bool targetInImage = target >= image.base && target - image.base < image.size;
    if (branch.child != child || !target || targetInImage ||
        !P::range(image,branch.instruction,5) ||
        image.bytes[branch.instruction] != branch.opcode) return false;
    if (branch.opcode == 0xe8)
        return P::externalCall(image,branch.instruction,target);
    if (branch.opcode == 0xe9)
        return verifyRelativeBranch(image,branch.instruction,target,0xe9);
    return false;
}

inline void hashNormalizedRange(SHA::Sha256Context *context,
                                const P::Image &image, ChildKind child,
                                size_t start, size_t end) {
    size_t cursor=start;
    while (cursor<end) {
        size_t operand=SIZE_MAX;
        for (size_t index=0;index<ExternalCallCount;++index) {
            const ExternalCall &branch=ExternalCalls[index];
            if (branch.child!=child || branch.instruction>SIZE_MAX-5) continue;
            const size_t candidate=branch.instruction+1;
            if (candidate>=cursor && candidate<end &&
                branch.instruction+5<=end && candidate<operand)
                operand=candidate;
        }
        if (operand==SIZE_MAX) {
            while (cursor<end) SHA::sha256Byte(context,image.bytes[cursor++]);
            break;
        }
        while (cursor<operand) SHA::sha256Byte(context,image.bytes[cursor++]);
        for (size_t byte=0;byte<4;++byte) SHA::sha256Byte(context,0);
        cursor=operand+4;
    }
}

inline bool verifyFunction(const P::Image &image, ChildKind child,
                           const FunctionContract &function) {
    if (!function.symbol || !function.normalizedSHA256 || function.end <= function.start ||
        !P::range(image,function.start,function.end-function.start)) return false;
    SHA::Sha256Context context {};
    SHA::sha256Init(&context);
    hashNormalizedRange(&context,image,child,function.start,function.end);
    uint8_t digest[32];
    SHA::sha256Finish(&context,digest);
    return memcmp(digest,function.normalizedSHA256,sizeof(digest))==0;
}

inline bool verifyCodeRange(const P::Image &image, ChildKind child,
                            const CodeRangeContract &range) {
    if (range.child!=child || !range.sha256 || range.end<=range.start ||
        !P::range(image,range.start,range.end-range.start)) return false;
    SHA::Sha256Context context {};
    SHA::sha256Init(&context);
    hashNormalizedRange(&context,image,child,range.start,range.end);
    uint8_t digest[32];
    SHA::sha256Finish(&context,digest);
    return memcmp(digest,range.sha256,sizeof(digest))==0;
}

inline bool addressInImage(const P::Image &image, uintptr_t address) {
    return address >= image.base && address - image.base < image.size;
}

inline bool verifyRelativeTableEntry(const P::Image &image,
                                    const RelativeTableEntry &entry) {
    if (!P::range(image,entry.entryOffset,sizeof(int32_t)) ||
        entry.tableBase>static_cast<size_t>(INT64_MAX) ||
        entry.targetOffset>static_cast<size_t>(INT64_MAX)) return false;
    int32_t displacement=0;
    memcpy(&displacement,image.bytes+entry.entryOffset,sizeof(displacement));
    const int64_t resolved=static_cast<int64_t>(entry.tableBase)+displacement;
    return resolved>=0 && static_cast<uint64_t>(resolved)==entry.targetOffset;
}

inline bool verifyRelativeJump(const P::Image &image, ChildKind child,
                               const RelativeJump &jump) {
    if (jump.child!=child || !P::range(image,jump.instruction,5) ||
        !P::range(image,jump.targetOffset,1) ||
        image.bytes[jump.instruction]!=0xe9) return false;
    int32_t displacement=0;
    memcpy(&displacement,image.bytes+jump.instruction+1,sizeof(displacement));
    const int64_t resolved=static_cast<int64_t>(jump.instruction+5)+displacement;
    return resolved>=0 && static_cast<uint64_t>(resolved)==jump.targetOffset;
}

inline bool verifyRelativeConditionalBranch(
    const P::Image &image, ChildKind child,
    const RelativeConditionalBranch &branch) {
    if (branch.child!=child || !P::range(image,branch.instruction,2) ||
        !P::range(image,branch.targetOffset,1) ||
        image.bytes[branch.instruction]!=branch.opcode) return false;
    const int8_t displacement=static_cast<int8_t>(image.bytes[branch.instruction+1]);
    const int64_t resolved=static_cast<int64_t>(branch.instruction+2)+displacement;
    return resolved>=0 && static_cast<uint64_t>(resolved)==branch.targetOffset;
}

inline bool callsiteReturnPCMatches(const P::Image &image, size_t instruction,
                                   size_t targetOffset,
                                   uintptr_t returnPC) {
    if (instruction > SIZE_MAX - 5 ||
        !P::range(image,instruction,5) ||
        !P::range(image,targetOffset,1)) return false;
    return returnPC == image.base + instruction + 5 &&
        P::call(image,instruction,image.base + targetOffset);
}

