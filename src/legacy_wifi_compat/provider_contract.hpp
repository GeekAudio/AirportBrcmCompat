inline bool range(const Image &image, size_t offset, size_t count) {
    return image.bytes && image.base && image.size <= UINTPTR_MAX-image.base &&
        offset <= image.size && count <= image.size-offset;
}
template<size_t N>
inline bool bytes(const Image &image, size_t offset, const uint8_t (&expected)[N]) {
    return range(image,offset,N) && !memcmp(image.bytes+offset,expected,N);
}
inline bool call(const Image &image, size_t offset, uintptr_t target) {
    if (!range(image,offset,5) || image.bytes[offset]!=0xe8 || target<image.base ||
        target-image.base>=image.size) return false;
    int32_t delta=0;memcpy(&delta,image.bytes+offset+1,4);
    const int64_t resolved=static_cast<int64_t>(offset)+5+delta;
    return resolved>=0 && static_cast<uint64_t>(resolved)==target-image.base;
}
inline bool ripRelativeTarget(const Image &image, size_t instructionOffset,
        size_t instructionLength, size_t displacementOffset, uintptr_t &target) {
    if (displacementOffset > instructionLength ||
        instructionLength - displacementOffset < sizeof(int32_t) ||
        !range(image, instructionOffset, instructionLength)) return false;
    int32_t encoded = 0;
    memcpy(&encoded, image.bytes + instructionOffset + displacementOffset,
           sizeof(encoded));
    const uintptr_t origin = image.base + instructionOffset + instructionLength;
    const int64_t delta = encoded;
    if (delta < 0) {
        const uintptr_t magnitude = static_cast<uintptr_t>(-delta);
        if (origin < magnitude) return false;
        target = origin - magnitude;
    } else {
        const uintptr_t magnitude = static_cast<uintptr_t>(delta);
        if (magnitude > UINTPTR_MAX - origin) return false;
        target = origin + magnitude;
    }
    return target >= image.base && target - image.base < image.size;
}
// External x86_64 Mach-O BRANCH relocations patch the signed rel32 operand in
// place. The destination can be outside this kext image, so keep this distinct
// from call(), which is for pinned intra-image targets.
inline bool externalCall(const Image &image,size_t offset,uintptr_t target) {
    if (!range(image,offset,5) || image.bytes[offset]!=0xe8 || !target ||
        offset>UINTPTR_MAX-image.base-5) return false;
    const uintptr_t returnPC=image.base+offset+5;
    int64_t expected=0;
    if (target>=returnPC) {
        const uint64_t distance=target-returnPC;
        if (distance>static_cast<uint64_t>(INT32_MAX)) return false;
        expected=static_cast<int64_t>(distance);
    } else {
        const uint64_t distance=returnPC-target;
        if (distance>0x80000000ULL) return false;
        expected=-static_cast<int64_t>(distance);
    }
    int32_t actual=0;memcpy(&actual,image.bytes+offset+1,sizeof(actual));
    return actual==expected;
}
template<size_t N>
inline bool bytesExceptExternalCallDisplacements(const Image &image,size_t offset,
        const uint8_t (&expected)[N],size_t firstCall,size_t secondCall) {
    if (!range(image,offset,N) || firstCall+5>N || secondCall+5>N) return false;
    for (size_t index=0;index<N;index++) {
        const bool relocated=(index>firstCall && index<firstCall+5) ||
                             (index>secondCall && index<secondCall+5);
        if (!relocated && image.bytes[offset+index]!=expected[index]) return false;
    }
    return true;
}
